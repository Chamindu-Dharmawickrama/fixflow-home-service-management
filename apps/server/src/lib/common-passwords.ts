const COMMON_PASSWORD_SET: ReadonlySet<string> = new Set(COMMON_PASSWORDS);

/** Lower-case, letters and digits only: the form the list is stored in. */
export function normalizeForCommonCheck(password: string): string {
  return password.toLowerCase().replace(/[^\p{L}\p{N}]/gu, "");
}

/** True when the password is (a trivial variation of) one of the bundled common passwords. */
export function isCommonPassword(password: string): boolean {
  return COMMON_PASSWORD_SET.has(normalizeForCommonCheck(password));
}
